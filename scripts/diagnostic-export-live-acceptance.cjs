// Disposable actual main Server only; downloads contain synthetic diagnostics.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const crypto = require('node:crypto')
const base = process.env.DIAGNOSTIC_TEST_URL
if (!base || !['127.0.0.1', 'localhost'].includes(new URL(base).hostname)) throw new Error('Disposable local Server required')
;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ acceptDownloads: true })
  try {
    const page = await context.newPage(), errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(base + '/admin?tab=health')
    await page.getByLabel('密码', { exact: true }).fill('diagnostic-local-test-password')
    const login = page.waitForResponse(r => r.url().endsWith('/api/v1/auth/login'))
    await page.getByRole('button', { name: '使用密码登录' }).click()
    const csrf = (await (await login).json()).csrf_token
    const create = await context.request.post(base + '/api/v1/admin/nodes', { headers: { 'X-CSRF-Token': csrf }, data: { name: 'synthetic-private-node', collection_seconds: 5, report_seconds: 5 } })
    assert.equal(create.status(), 201)
    const created = await create.json()
    const card = page.locator('.diagnostic-export')
    await card.getByRole('heading', { name: '导出脱敏诊断' }).waitFor()
    const response = page.waitForResponse(r => r.url().endsWith('/diagnostic-exports/preview'))
    await card.getByRole('button', { name: '生成诊断预览' }).click()
    const prepared = await (await response).json()
    assert.equal(prepared.bundle.configuration_counts.counts.nodes, 1)
    assert.equal(prepared.bundle.runtime.version.base, '1.2.3')
    assert.equal(prepared.bundle.workers.latency_scheduler.status, 'running')
    assert.equal(prepared.bundle.notification_queue.status, 'available')
    const serialized = JSON.stringify(prepared)
    for (const privateValue of ['203.0.113.9', 'private-build', 'synthetic-private-node', created.node.id, created.token, csrf, process.env.DIAGNOSTIC_TEST_PRIVATE_KEY, process.env.DIAGNOSTIC_TEST_PRIVATE_PATH, 'example.invalid']) {
      if (privateValue) assert.equal(serialized.includes(privateValue), false, 'private value leaked')
    }
    const later = await context.request.post(base + '/api/v1/admin/nodes', { headers: { 'X-CSRF-Token': csrf }, data: { name: 'after-preview', collection_seconds: 5, report_seconds: 5 } })
    assert.equal(later.status(), 201)
    const downloadEvent = page.waitForEvent('download')
    await card.getByRole('button', { name: '下载已预览的 JSON' }).click()
    const download = await downloadEvent
    assert.equal(download.suggestedFilename(), prepared.preview.file_name)
    const data = await fs.readFile(await download.path())
    assert.equal(data.byteLength, prepared.preview.bytes)
    assert.equal(crypto.createHash('sha256').update(data).digest('hex'), prepared.preview.sha256)
    assert.equal(JSON.parse(data).configuration_counts.counts.nodes, 1)
    const audit = await (await context.request.get(base + '/api/v1/admin/audit?limit=50')).json()
    const exportEntry = audit.entries.find(entry => entry.object_type === 'diagnostic_bundle')
    assert.ok(exportEntry)
    assert.equal(exportEntry.object_id, prepared.preview.preview_id)
    assert.equal(exportEntry.details.result, 'response_prepared')
    const output = path.join(os.tmpdir(), 'myprobe-diagnostic-export-live-ui')
    await fs.mkdir(output, { recursive: true })
    for (const theme of ['light', 'dark']) for (const width of [360, 768, 1440]) {
      await page.setViewportSize({ width, height: 1000 })
      await page.evaluate(theme => { document.documentElement.dataset.theme = theme }, theme)
      await card.scrollIntoViewIfNeeded()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${theme}/${width} overflow`)
      await page.screenshot({ path: path.join(output, `${theme}-${width}.png`) })
      await card.getByText('查看本次文件内容', { exact: true }).click()
      assert.equal(await card.locator('pre').isVisible(), true)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      await page.screenshot({ path: path.join(output, `${theme}-${width}-content.png`) })
      await card.getByText('查看本次文件内容', { exact: true }).click()
    }
    await context.request.post(base + '/api/v1/auth/logout', { headers: { 'X-CSRF-Token': csrf } })
    await card.getByRole('button', { name: '下载已预览的 JSON' }).click()
    await page.getByRole('heading', { name: '登录管理中心', exact: true }).waitFor()
    assert.equal(await page.locator('.diagnostic-export pre').count(), 0)
    assert.deepEqual(errors, [])
    console.log(`PASS: actual main Server, private preview, frozen download bytes/hash, source mutation, audit gate, version privacy, six viewports/themes and session revocation. Screenshots: ${output}`)
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
