const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict'), ts = require('../node_modules/typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/network-quality/time.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const box = { exports: {} }; new Function('module', 'exports', compiled)(box, box.exports);
const { localInstant: instant, localInput: input, lastEvening: peak, customRange: range } = box.exports;
assert.equal(new Date(instant('2026-03-08T03:30', 'America/New_York')).toISOString(), '2026-03-08T07:30:00.000Z');
assert.throws(() => instant('2026-03-08T02:30', 'America/New_York'), /跳时/);
assert.throws(() => instant('2026-11-01T01:30', 'America/New_York'), /重复/);
assert.throws(() => instant('2026-02-30T12:00', 'UTC'), /无效/);
assert.throws(() => instant('2026-01-01T24:00', 'UTC'), /无效/);
const now = Date.parse('2026-10-15T14:00:00Z');
assert.deepEqual(peak(now, 'Asia/Shanghai'), { start: '2026-10-14T11:00:00.000Z', end: '2026-10-14T15:00:00.000Z' });
assert.deepEqual(peak(Date.parse('2026-10-15T15:00:00Z'), 'Asia/Shanghai'), { start: '2026-10-15T11:00:00.000Z', end: '2026-10-15T15:00:00.000Z' });
const dst = range('2026-03-08T01:30', '2026-03-08T03:30', 'America/New_York', now);
assert.equal(Date.parse(dst.end) - Date.parse(dst.start), 3600000);
assert.equal(input(Date.parse('2026-03-08T16:30:00Z'), 'Asia/Shanghai'), '2026-03-09T00:30');
assert.throws(() => range('2026-10-15T12:00', '2026-10-15T11:00', 'UTC', now));
assert.throws(() => range('2026-10-15T14:00', '2026-10-15T15:00', 'UTC', now));
assert.throws(() => range('2024-01-01T00:00', '2026-01-01T00:00', 'UTC', now));
console.log('Network quality time-zone and peak contracts passed.');
